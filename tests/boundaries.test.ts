import { randomUUID } from "node:crypto";
import {
  mkdir,
  mkdtemp,
  realpath,
  rm,
  symlink,
  utimes,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, test } from "vitest";
import { parseModelResponse } from "../src/model/adapters/deepseek.ts";
import {
  createTraceWriter,
  listTraces,
  replayTrace,
  writeTraceEvent,
} from "../src/telemetry/trace.ts";
import { validateToolCall } from "../src/tools/contracts.ts";

describe("tool-call validation", () => {
  test("accepts a valid read_file call", () => {
    expect(
      validateToolCall({
        type: "read_file",
        path: "README.md",
      }),
    ).toEqual({
      ok: true,
      call: {
        type: "read_file",
        path: "README.md",
      },
    });
  });

  test("returns a structured error for an unknown tool", () => {
    const result = validateToolCall({ type: "delete_file" });

    expect(result.ok).toBe(false);

    if (!result.ok) {
      expect(result.error.code).toBe("INVALID_TOOL_CALL");
    }
  });
});

describe("DeepSeek response parsing", () => {
  test("parses multiple tool calls from one model turn", () => {
    const result = parseModelResponse({
      choices: [
        {
          message: {
            role: "assistant",
            content: "Inspecting both files.",
            reasoning_content: "",
            tool_calls: [
              {
                id: "call_1",
                type: "function",
                function: {
                  name: "read_file",
                  arguments: '{"path":"package.json"}',
                },
              },
              {
                id: "call_2",
                type: "function",
                function: {
                  name: "read_file",
                  arguments: '{"path":"README.md"}',
                },
              },
            ],
          },
        },
      ],
    });

    expect(result.ok).toBe(true);

    if (result.ok) {
      expect(result.action.type).toBe("tool_calls");

      if (result.action.type === "tool_calls") {
        expect(result.action.calls).toHaveLength(2);
      }
    }
  });

  test("rejects malformed JSON tool arguments", () => {
    const result = parseModelResponse({
      choices: [
        {
          message: {
            role: "assistant",
            content: null,
            tool_calls: [
              {
                id: "call_1",
                type: "function",
                function: {
                  name: "read_file",
                  arguments: "{not-json}",
                },
              },
            ],
          },
        },
      ],
    });

    expect(result.ok).toBe(false);

    if (!result.ok) {
      expect(result.error.code).toBe("INVALID_MODEL_RESPONSE");
    }
  });
});

const temporaryWorkspaces: string[] = [];

async function createWorkspace(): Promise<string> {
  // Resolve the real path because macOS puts temporary files behind a
  // symlinked /var, and the trace checks compare real paths to the root.
  const directory = await realpath(
    await mkdtemp(join(tmpdir(), "itemd-trace-test-")),
  );

  temporaryWorkspaces.push(directory);

  return directory;
}

async function writeRawTrace(
  workspaceRoot: string,
  lines: string[],
): Promise<string> {
  const traceId = randomUUID();
  const traceDirectory = join(workspaceRoot, ".itemd", "traces");

  await mkdir(traceDirectory, { recursive: true });
  await writeFile(
    join(traceDirectory, `${traceId}.jsonl`),
    lines.join("\n"),
    "utf8",
  );

  return traceId;
}

afterEach(async () => {
  await Promise.all(
    temporaryWorkspaces.splice(0).map((directory) =>
      rm(directory, { recursive: true, force: true }),
    ),
  );
});

describe("trace replay", () => {
  test("rejects trace IDs that itemd did not generate", async () => {
    const workspaceRoot = await createWorkspace();

    for (const traceId of [
      "../../.env",
      "",
      // Version 8 UUID from another tool, not randomUUID().
      "25c1b0de-49d3-8d53-624a95ac2d3",
    ]) {
      await expect(replayTrace(workspaceRoot, traceId)).resolves.toEqual({
        ok: false,
        error: {
          code: "INVALID_TRACE_ID",
          message: "Trace ID must be a UUID generated by itemd",
        },
      });
    }
  });

  test("round-trips a recorded run without model or tool access", async () => {
    const workspaceRoot = await createWorkspace();
    const writer = await createTraceWriter(workspaceRoot);

    await writeTraceEvent(writer, {
      type: "run_start",
      timestamp: "2026-01-01T00:00:00.000Z",
      task: "read package.json",
      provider: "deepseek",
      model: "deepseek-flash",
      effort: "high",
      mode: "agent",
      maxSteps: 50,
    });
    await writeTraceEvent(writer, {
      type: "run_end",
      timestamp: "2026-01-01T00:00:02.000Z",
      result: {
        ok: true,
        status: "done",
        answer: "DONE: package name is itemd",
        steps: 1,
        traceId: writer.id,
        tracePath: writer.relativePath,
      },
    });

    const result = await replayTrace(workspaceRoot, writer.id);

    expect(result.ok).toBe(true);

    if (result.ok) {
      expect(result.traceId).toBe(writer.id);
      expect(result.events).toHaveLength(2);
      expect(result.events[0]).toMatchObject({
        type: "run_start",
        task: "read package.json",
      });
      expect(result.events[1]).toMatchObject({ type: "run_end" });
    }
  });

  test("treats a missing trace directory as an empty list", async () => {
    const workspaceRoot = await createWorkspace();

    await expect(listTraces(workspaceRoot)).resolves.toEqual({
      ok: true,
      traces: [],
    });
  });

  test("lists only itemd traces, newest first", async () => {
    const workspaceRoot = await createWorkspace();
    const older = await writeRawTrace(workspaceRoot, ["{}"]);
    const newer = await writeRawTrace(workspaceRoot, ["{}"]);
    const traceDirectory = join(workspaceRoot, ".itemd", "traces");

    await utimes(
      join(traceDirectory, `${older}.jsonl`),
      new Date("2020-01-01T00:00:00.000Z"),
      new Date("2020-01-01T00:00:00.000Z"),
    );
    await utimes(
      join(traceDirectory, `${newer}.jsonl`),
      new Date("2021-01-01T00:00:00.000Z"),
      new Date("2021-01-01T00:00:00.000Z"),
    );
    await writeFile(join(traceDirectory, "notes.jsonl"), "{}\n", "utf8");

    const result = await listTraces(workspaceRoot);

    expect(result.ok).toBe(true);

    if (result.ok) {
      expect(result.traces.map((trace) => trace.traceId)).toEqual([
        newer,
        older,
      ]);
    }
  });

  test("reports a read failure when the trace file is missing", async () => {
    const workspaceRoot = await createWorkspace();

    await mkdir(join(workspaceRoot, ".itemd", "traces"), {
      recursive: true,
    });

    await expect(
      replayTrace(workspaceRoot, randomUUID()),
    ).resolves.toMatchObject({
      ok: false,
      error: { code: "TRACE_READ_FAILED" },
    });
  });

  test("reports the first malformed trace line", async () => {
    const workspaceRoot = await createWorkspace();
    const traceId = await writeRawTrace(workspaceRoot, [
      JSON.stringify({ type: "run_start" }),
      "{not-json}",
    ]);

    await expect(replayTrace(workspaceRoot, traceId)).resolves.toEqual({
      ok: false,
      error: {
        code: "TRACE_PARSE_FAILED",
        message: "Trace line 2 is not valid JSON",
      },
    });
  });

  test("rejects a trace that resolves outside the trace directory", async () => {
    if (process.platform === "win32") {
      return;
    }

    const workspaceRoot = await createWorkspace();
    const outsideRoot = await createWorkspace();
    const traceId = randomUUID();
    const outsidePath = join(outsideRoot, `${traceId}.jsonl`);

    await writeFile(outsidePath, "{}\n", "utf8");
    await mkdir(join(workspaceRoot, ".itemd", "traces"), {
      recursive: true,
    });
    await symlink(
      outsidePath,
      join(workspaceRoot, ".itemd", "traces", `${traceId}.jsonl`),
    );

    await expect(replayTrace(workspaceRoot, traceId)).resolves.toEqual({
      ok: false,
      error: {
        code: "TRACE_READ_FAILED",
        message: "Trace resolves outside the trace directory",
      },
    });
  });
});
